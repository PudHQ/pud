import { execFile } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { promisify } from "node:util";
import type { Transaction } from "./lower.ts";

const exec = promisify(execFile);
const require = createRequire(import.meta.url);

// The projected TS declares the SQL boundary so lsc can typecheck control flow.
// Only its generated method body is linked. The final verification unit supplies
// concrete database definitions for every external call and proves each contract.
export async function compileTransaction(plan: Transaction, dir: string): Promise<string> {
  const source = join(dir, "transaction.ts");
  await writeFile(source, plan.source);
  try {
    await exec(process.execPath, [require.resolve("lemmascript/tools/dist/lsc.js"), "gen", "--backend=dafny", source],
      { cwd: dir, timeout: 45_000, maxBuffer: 1024 * 1024 });
  } catch (error) {
    const e = error as { stderr?: string; message: string };
    throw new Error(`LemmaScript could not translate the transaction: ${e.stderr?.trim() || e.message}`);
  }
  const output = (await readFile(join(dir, "transaction.dfy.gen"), "utf8")).replaceAll("\r\n", "\n");
  const signature = "method pudTransaction(s: State, q: Request) returns (res: Outcome)\n";
  const [declarations, body, extra] = output.split("\n" + signature);
  if (extra !== undefined || !body?.startsWith("{\n") || !body.trimEnd().endsWith("}")) {
    throw new Error("Unexpected LemmaScript output for the transaction method");
  }
  const supplied = new Set([
    "// Generated by lsc from transaction.ts",
    "datatype State = State(opaqueId: int)",
    "datatype Request = Request(tenant: string, account: string, requestId: string, amount: int)",
    "datatype QueryResult = QueryResult(after: State, rowCount: int)",
    "datatype Outcome = Outcome(status: string, after: State, closed: bool)",
    ...plan.operations.map(name => `function {:axiom} ${name}(working: State, q: Request): QueryResult`),
  ]);
  for (const line of declarations!.split("\n").filter(Boolean)) {
    if (!supplied.delete(line)) throw new Error(`Unexpected declaration from LemmaScript: ${line}`);
  }
  if (/^\s*(?:assume\b|.*\{:(?:axiom|verify\s+false)\})/m.test(body)) throw new Error("Unexpected assumption in the generated method");
  return body;
}
